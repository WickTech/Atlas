import { Sparkles } from "lucide-react";

import type { Briefs } from "@/types/metrics";

const PROVIDER_LABEL: Record<Briefs["source"], string> = { groq: "Groq", openrouter: "OpenRouter", "rule-based": "rule-based" };

// AI / rule-based news briefs. A badge shows which provider produced the brief
// (or that the deterministic fallback was used) — never implied AI when it isn't.
export function AiBriefs({ briefs }: { briefs: Briefs }) {
  const isAi = briefs.source !== "rule-based";

  return (
    <article className="@container p-4">
      <div className="mb-3 flex items-center justify-between">
        <h2 className="text-base font-semibold">Today&apos;s briefing</h2>
        <span
          className={`chip ${isAi ? "bg-accent-soft text-accent-400" : "bg-surface-2 text-muted"}`}
          title={isAi ? `Generated by ${briefs.model ?? PROVIDER_LABEL[briefs.source]}` : "Deterministic digest (no LLM available)"}
        >
          {isAi && <Sparkles size={11} aria-hidden="true" />}
          {isAi ? `AI · ${PROVIDER_LABEL[briefs.source]}` : "rule-based"}
        </span>
      </div>

      <div className="grid grid-cols-1 gap-3 @2xl:grid-cols-2">
        <div className="border border-border bg-surface-2 p-3">
          <p className="mb-1 text-xs font-semibold tracking-wide text-accent-400 uppercase">🇮🇳 India brief</p>
          <p className="text-sm leading-relaxed text-fg">{briefs.india || "—"}</p>
        </div>
        {briefs.global ? (
          <div className="border border-border bg-surface-2 p-3">
            <p className="mb-1 text-xs font-semibold tracking-wide text-muted uppercase">🌍 Global brief</p>
            <p className="text-sm leading-relaxed text-fg">{briefs.global}</p>
          </div>
        ) : null}
      </div>

      {briefs.categories.length ? (
        <div className="mt-3 grid grid-cols-1 gap-2 @md:grid-cols-2">
          {briefs.categories.slice(0, 6).map((c) => (
            <div key={c.label} className="border border-border p-2.5">
              <p className="text-xs font-semibold text-muted">{c.label}</p>
              <p className="text-sm text-fg">{c.text}</p>
            </div>
          ))}
        </div>
      ) : null}
    </article>
  );
}
